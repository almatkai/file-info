#!/usr/bin/env python3
"""All media content is generated here; no user media is read."""
import hashlib,json,math,os,pathlib,struct,subprocess,wave,zlib
V2=pathlib.Path(__file__).resolve().parents[1];QA=V2/'.qa';D=QA/'fixtures';D.mkdir(exist_ok=True)
EXIF=QA/'tools/exiftool-13.40/exiftool'
assert pathlib.Path(os.environ['HOME']).is_relative_to(QA)
def run(args):
 p=subprocess.run([str(x) for x in args],capture_output=True,timeout=60)
 if p.returncode:raise RuntimeError(p.stderr.decode(errors='replace'))
 return p.stdout
def exif(args):return run(['/usr/bin/perl',EXIF,'-config','',*args])
def chunk(t,b):return struct.pack('>I',len(b))+t+b+struct.pack('>I',zlib.crc32(t+b))
png=b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',2,2,8,2,0,0,0))+chunk(b'tEXt',b'Author\0Owned QA')+chunk(b'IDAT',zlib.compress(b'\0\xff\0\0\0\xff\0\0\0\0\xff\xff\xff\xff'))+chunk(b'IEND',b'')
(D/'own.png').write_bytes(png)
for fmt,ext in [('jpeg','jpg'),('tiff','tiff'),('gif','gif')]:run(['/usr/bin/sips','-s','format',fmt,D/'own.png','--out',D/f'own.{ext}'])
run(['/opt/homebrew/bin/cwebp','-lossless',D/'own.png','-o',D/'own.webp'])
with wave.open(str(D/'own.wav'),'wb') as w:
 w.setnchannels(1);w.setsampwidth(2);w.setframerate(8000);w.writeframes(b''.join(struct.pack('<h',int(math.sin(i*.3)*1000)) for i in range(800)))
for ext in ['flac','mp3','m4a']:run(['/opt/homebrew/bin/ffmpeg','-y','-v','error','-i',D/'own.wav','-metadata','title=Owned QA',D/f'own.{ext}'])
run(['/opt/homebrew/bin/ffmpeg','-y','-v','error','-loop','1','-i',D/'own.png','-t','0.2','-c:v','mpeg4','-pix_fmt','yuv420p','-metadata','title=Owned QA',D/'own.mp4'])
run(['/opt/homebrew/bin/ffmpeg','-y','-v','error','-loop','1','-i',D/'own.png','-t','0.2','-c:v','mpeg4','-pix_fmt','yuv420p','-metadata','title=Owned QA',D/'own.mov'])
# A minimal authored PDF, with correct object offsets/xref, no external resources.
objects=[b'<< /Type /Catalog /Pages 2 0 R >>',b'<< /Type /Pages /Kids [3 0 R] /Count 1 >>',b'<< /Type /Page /Parent 2 0 R /MediaBox [0 0 100 100] /Contents 4 0 R >>',b'<< /Length 23 >>\nstream\n0 0 1 rg 0 0 20 20 re f\nendstream',b'<< /Author (Owned QA) >>']
pdf=b'%PDF-1.4\n';offsets=[0]
for n,obj in enumerate(objects,1):offsets.append(len(pdf));pdf+=f'{n} 0 obj\n'.encode()+obj+b'\nendobj\n'
xref=len(pdf);pdf+=b'xref\n0 6\n0000000000 65535 f \n'+b''.join(f'{x:010} 00000 n \n'.encode() for x in offsets[1:]);pdf+=f'trailer\n<< /Size 6 /Root 1 0 R /Info 5 0 R >>\nstartxref\n{xref}\n%%EOF\n'.encode();(D/'own.pdf').write_bytes(pdf)
for ext in ['jpg','png','tiff','webp','pdf']:
 exif(['-overwrite_original','-XMP-dc:Creator=Owned QA',D/f'own.{ext}'])
exif(['-overwrite_original','-Comment=Owned QA',D/'own.gif'])
# WAV/FLAC/MP3 are read-only in ExifTool 13.40: fixture tags come from encoder, never claim writable support.
(D/'bad.png').write_bytes(png[:-1]);(D/'plain.txt').write_text('Owned QA text\n');(D/'unicode\nфайл ; $().txt').write_text('Owned QA unicode\n')
BIN=QA/'bin';BIN.mkdir(exist_ok=True)
def fake(name,body):
 p=BIN/name;p.write_text('#!/bin/sh\n'+body+'\n');p.chmod(0o700)
fake('exiftool',f'exec /usr/bin/perl "{EXIF}" "$@"')
fake('ls',"printf '%s\\n' '-rw-r--r-- 1 qa-owner qa-group 42 owned'")
fake('file',"printf '%s\\n' 'application/octet-stream'")
fake('ffprobe',"case \"$*\" in *stream=width,height*) printf '%s\\n' '2x2';; *) printf '%s\\n' '1.25';; esac")
# Fake native output helpers only print fixed owned data, never examine paths.
for name in ['sips','mdls','afinfo']:fake(name,'exit 1')
records=[]
for p in sorted(D.iterdir()):
 if p.is_file():records.append({'path':p.name,'sha256':hashlib.sha256(p.read_bytes()).hexdigest(),'bytes':p.stat().st_size,'origin':'generated by scripts/fixtures.py; authored test content; MIT'})
(V2/'fixtures/generated-media.json').write_text(json.dumps(records,indent=2)+'\n')
print(f'{len(records)} generated owned fixtures; no user files')
